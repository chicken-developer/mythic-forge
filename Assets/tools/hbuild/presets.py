"""Presets = a JSON dict of HDA parameter values that makes the generator match one concept.

File format (presets/<asset>.json):
{
  "name": "townhouse_a",
  "generator": "bldg::building_generator::1.0",
  "concept": ["concepts/townhouse_a/front.png"],
  "notes": "what was estimated, what is unknown",
  "parms": { "width": 10.0, "col_wall": [0.78, 0.68, 0.55], "upper_front": "W", ... }
}
The same functions are embedded in the HDA PythonModule (see hda.py), so presets can be
applied from the HDA UI, from hython (hb.py) and from Houdini Engine in Unreal.
"""
import json

SECTION = "presets.json"     # HDA section that stores the embedded presets {name: preset}


def load_file(path):
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def save_file(path, preset):
    with open(path, "w", encoding="utf-8") as f:
        json.dump(preset, f, indent=2, sort_keys=False)


def validate(preset, specs):
    """Return a list of problems (unknown parms, values out of the soft range)."""
    known = {p.name: p for p in specs}
    issues = []
    for k, v in preset.get("parms", {}).items():
        p = known.get(k)
        if p is None:
            issues.append("unknown parm '%s'" % k)
            continue
        if p.kind in ("float", "int") and isinstance(v, (int, float)):
            if p.lo is not None and v < p.lo:
                issues.append("%s=%s below %s" % (k, v, p.lo))
            if p.hi is not None and v > p.hi:
                issues.append("%s=%s above soft max %s (allowed, but check)" % (k, v, p.hi))
        if p.kind == "color" and (not isinstance(v, (list, tuple)) or len(v) != 3):
            issues.append("%s must be [r,g,b]" % k)
    return issues


def apply_values(node, values):
    """Set parms on `node` from a dict. Returns names that the node does not have."""
    missing = []
    for k, v in values.items():
        pt = node.parmTuple(k)
        if pt is None:
            missing.append(k)
            continue
        if isinstance(v, (list, tuple)):
            pt.set(tuple(v))
        else:
            pt.set((v,))
    return missing


def read_values(node, keys):
    out = {}
    for k in keys:
        pt = node.parmTuple(k)
        if pt is None:
            continue
        vals = pt.eval()
        out[k] = list(vals) if len(vals) > 1 else vals[0]
    return out


# ---- the code below is copied verbatim into the HDA PythonModule ----
PYTHON_MODULE = r'''
"""PythonModule of the hbuild generator HDA (generated by hbuild/hda.py - edit there)."""
import json
import hou

SECTION = "presets.json"


def _defn(node):
    return node.type().definition()


def load_presets(node):
    d = _defn(node)
    if d is not None and SECTION in d.sections():
        return json.loads(d.sections()[SECTION].contents() or "{}")
    return {}


def preset_menu(node):
    items = []
    for name in sorted(load_presets(node)):
        items += [name, name]
    return items or ["", "(no presets embedded)"]


def apply_preset(node, name=None):
    name = name or node.evalParm("preset")
    data = load_presets(node).get(name)
    if not data:
        raise hou.NodeError("Preset '%s' not found in %s" % (name, SECTION))
    missing = []
    for k, v in data.get("parms", {}).items():
        pt = node.parmTuple(k)
        if pt is None:
            missing.append(k)
            continue
        pt.set(tuple(v) if isinstance(v, (list, tuple)) else (v,))
    if missing:
        print("[preset %s] parms not on this HDA version: %s" % (name, ", ".join(missing)))


def save_preset(node, name):
    """Store the current values as preset `name` inside the HDA definition (needs a writable .hda)."""
    keys = [p.name() for p in node.parms() if p.parmTemplate().type() != hou.parmTemplateType.Button
            and p.name() != "preset"]
    values = {}
    for pt in node.parmTuples():
        if pt.name() in ("preset",) or pt.parmTemplate().type() == hou.parmTemplateType.Button:
            continue
        v = pt.eval()
        values[pt.name()] = list(v) if len(v) > 1 else v[0]
    presets = load_presets(node)
    presets[name] = {"name": name, "generator": node.type().name(), "parms": values}
    _defn(node).addSection(SECTION, json.dumps(presets, indent=2))
'''
